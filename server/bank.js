// What the browser may know about the questions.
//
// shared/questions.js holds everything, right answers included, and only ever runs on the server
// (and in the scripts). Browsers get an index instead: enough to choose a Quick round, and nothing
// that says what a question asks or which option is right. The rest comes from the server, one
// round at a time (questionContent), or one question at a time in a Daily or duel (server/play.js).

import { QUESTIONS, QUESTION_BY_ID } from '../shared/questions.js';

// `about` often is the answer ("France"). Quick rounds only need to know which questions share one.
const subjects = new Map();
function subjectToken(q) {
  if (!q.about) return undefined;
  const key = q.about.toLowerCase();
  if (!subjects.has(key)) subjects.set(key, `s${subjects.size + 1}`);
  return subjects.get(key);
}

const index = QUESTIONS.map((q) => ({ id: q.id, cat: q.cat, difficulty: q.difficulty, about: subjectToken(q) }));

/** The module served at /shared/questions.js, in place of the real file. */
export const BROWSER_BANK = `// Generated by server/bank.js. The questions themselves come from the server as they're played.
export const QUESTIONS = ${JSON.stringify(index)};
export const QUESTION_BY_ID = new Map(QUESTIONS.map((q) => [q.id, q]));
`;

/** The options of a question in a fixed order that says nothing about which is right. */
export const sortedOptions = (q) => [q.answer, ...q.wrong].sort();

/** A question in full, for a round that's about to use it or an answer the player has already given. */
export function questionContent(q) {
  return { id: q.id, cat: q.cat, prompt: q.prompt, visual: q.visual, options: sortedOptions(q), answer: q.answer, ownPrompt: q.ownPrompt };
}

/** { id: content } for the ids that exist. */
export function contentFor(ids) {
  const out = {};
  for (const id of ids) {
    const q = QUESTION_BY_ID.get(id);
    if (q) out[id] = questionContent(q);
  }
  return out;
}
